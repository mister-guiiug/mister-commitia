#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
pub enum AiAttributionPolicy {
    /// La traçabilité des contributions assistées par IA est exigée : la
    /// suppression des mentions est refusée. Valeur par défaut (conservatrice).
    #[default]
    #[serde(rename = "keep-required")]
    KeepRequired,
    #[serde(rename = "normalization-allowed")]
    NormalizationAllowed,
}

fn default_protected_trailers() -> Vec<String> {
    vec!["Signed-off-by".into()]
}

pub fn default_signature_patterns() -> Vec<String> {
    vec![
        "Generated with [Claude Code]".into(),
        "Generated with Claude Code".into(),
        "Generated by Claude Code".into(),
        "🤖 Generated with".into(),
        "Co-Authored-By: Claude <noreply@anthropic.com>".into(),
        "https://claude.ai/code".into(),
        "Co-authored-by: Copilot".into(),
    ]
}

pub fn default_convention_types() -> Vec<String> {
    [
        "feat", "fix", "refactor", "chore", "docs", "test", "ci", "perf", "build", "style",
        "revert",
    ]
    .iter()
    .map(|s| s.to_string())
    .collect()
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Governance {
    #[serde(default = "default_protected_trailers")]
    pub protected_trailers: Vec<String>,
    #[serde(default)]
    pub ai_attribution_policy: AiAttributionPolicy,
    #[serde(default = "default_signature_patterns")]
    pub signature_patterns: Vec<String>,
    #[serde(default = "default_convention_types")]
    pub convention_types: Vec<String>,
    /// Re-signe les commits produits par la réécriture si une clé de signature
    /// est configurée dans le dépôt (`user.signingkey` + `gpg.format`) — évite
    /// que la réécriture ne fasse perdre les signatures (B1). Défaut : off.
    #[serde(default)]
    pub resign_after_rewrite: bool,
}

impl Default for Governance {
    fn default() -> Self {
        Self {
            protected_trailers: default_protected_trailers(),
            ai_attribution_policy: AiAttributionPolicy::default(),
            signature_patterns: default_signature_patterns(),
            convention_types: default_convention_types(),
            resign_after_rewrite: false,
        }
    }
}

