#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum Risk {
    #[default]
    Low,
    Medium,
    High,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "op", rename_all = "snake_case")]
pub enum Operation {
    Reword {
        target: String,
        new_message: String,
    },
    /// Fusionne `targets` (contigus, ordre du segment) en un commit portant `new_message`.
    Squash {
        targets: Vec<String>,
        new_message: String,
    },
    /// Fusionne `targets` dans le premier d'entre eux en conservant son message.
    Fixup {
        targets: Vec<String>,
    },
    Drop {
        target: String,
        reason: String,
    },
    /// Ordre final des commits restants (leaders de groupes), du plus ancien au plus récent.
    Reorder {
        order: Vec<String>,
    },
    /// Découpe UN commit (C3) en plusieurs, par fichier : chaque `part` reçoit un
    /// sous-ensemble DISJOINT des fichiers modifiés par `target`, dans l'ordre
    /// donné. La réunion des `files` doit couvrir EXACTEMENT les fichiers du commit.
    /// Op exclusive (un plan de découpe ne contient qu'elle) ; segment linéaire.
    Split {
        target: String,
        parts: Vec<SplitPart>,
    },
}

/// Une part d'une découpe (C3) : les fichiers qui lui reviennent + son message.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct SplitPart {
    pub files: Vec<String>,
    pub message: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PlanOp {
    pub seq: u32,
    #[serde(flatten)]
    pub op: Operation,
    #[serde(default)]
    pub origin: String,
    #[serde(default)]
    pub risk: Risk,
    pub approved_by: Option<String>,
    pub approved_at: Option<String>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum PlanStatus {
    Draft,
    DryRunOk,
    Applied,
    RolledBack,
    Invalidated,
    /// Le rejeu du dry-run est EN PAUSE sur un conflit (C1) : résolution
    /// interactive attendue (résoudre → continuer, ou abandonner).
    Conflict,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Fingerprint {
    pub branch: String,
    pub tip: String,
    pub base: String,
}

/// Correspondance : plusieurs anciens SHA (groupe squashé) → un nouveau SHA.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ShaMapping {
    pub old: Vec<String>,
    pub new: String,
}

/// Un fichier en conflit pendant un rejeu (C1) : `content` porte les marqueurs
/// `<<<<<<<`/`=======`/`>>>>>>>` que l'utilisateur édite pour résoudre.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ConflictFile {
    pub path: String,
    pub content: String,
}

/// État d'un conflit de rejeu en pause (C1).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ConflictInfo {
    pub files: Vec<ConflictFile>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Plan {
    pub id: String,
    pub version: u32,
    pub repo_id: String,
    pub fingerprint: Fingerprint,
    pub status: PlanStatus,
    pub ops: Vec<PlanOp>,
    /// Hash du contenu (ops + empreinte) au moment du dernier dry-run réussi.
    pub dry_run_hash: Option<String>,
    pub preview_ref: Option<String>,
    pub backup_ref: Option<String>,
    pub backup_tag: Option<String>,
    pub mapping: Vec<ShaMapping>,
    pub created_at: String,
    pub dry_run_at: Option<String>,
    pub applied_at: Option<String>,
    pub error: Option<String>,
    /// Détail du conflit quand `status == Conflict` (C1).
    #[serde(default)]
    pub conflict: Option<ConflictInfo>,
}

